async function main() {
  // 1. หา/สร้างวาระ
  const festival = await prisma.festival.upsert({
    where: { name: FESTIVAL.name },
    update: {},
    create: FESTIVAL,
  });
  console.log(`✓ Festival: ${festival.name} (${festival.id})`);

  // 2. โหลด SubCommittee map (key "1".."8" -> id)
  const allSC = await prisma.subCommittee.findMany();
  const scIdByKey: Record<string, string> = {};
  for (const sc of allSC) {
    const m = sc.name.match(/^C(\d+)/);
    if (m) scIdByKey[m[1]] = sc.id;
  }
  const missing = PROPOSALS.flatMap((p) => p.scKeys).filter((k) => !scIdByKey[k]);
  if (missing.length) {
    console.error("❌ Missing sub-committees for keys:", [...new Set(missing)]);
    return;
  }

  // 3. ตรวจว่ามี proposal ในวาระนี้แล้วไหม (idempotent)
  const existing = await prisma.proposal.count({ where: { festivalId: festival.id } });
  if (existing > 0) {
    console.log(`ℹ️  วาระนี้มีข้อเสนออยู่แล้ว ${existing} ข้อ — ข้าม (ถ้าต้องการ seed ใหม่ ให้ลบก่อน)`);
    return;
  }

  // 4. สร้างข้อเสนอทั้ง 23 ข้อ
  for (let i = 0; i < PROPOSALS.length; i++) {
    const p = PROPOSALS[i];
    await prisma.proposal.create({
      data: {
        title: p.title,
        description: p.description,
        festivalId: festival.id,
        orderNumber: i + 1,
        subCommittees: {
          create: p.scKeys.map((k) => ({ subCommitteeId: scIdByKey[k] })),
        },
      },
    });
  }
  console.log(`✓ Seeded ${PROPOSALS.length} proposals into "${festival.name}"`);

  // สรุปจำนวนต่ออนุฯ
  const grouped: Record<string, number> = {};
  PROPOSALS.forEach((p) => p.scKeys.forEach((k) => { grouped[k] = (grouped[k] ?? 0) + 1; }));
  Object.entries(grouped).sort().forEach(([k, n]) => console.log(`  อนุฯ ${k}: ${n} ข้อ`));
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => prisma.$disconnect());
